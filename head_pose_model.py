import os
import pandas as pd
import numpy as np
from glob import glob
from pathlib import Path

IMG_EXTS = {'.jpg', '.jpeg', '.png', '.bmp', '.webp'}

def list_images(root):
    return [p for p in glob(os.path.join(root, '**', '*.*'), recursive=True)
            if os.path.splitext(p)[1].lower() in IMG_EXTS]

def build_image_index(root):
    # Map basename -> full path (unique in AFLW2000)
    idx = {}
    for p in list_images(root):
        idx[os.path.basename(p)] = p
    return idx

def normalize_cols(cols):
    # lower, remove spaces/()/_ to make matching robust
    out = []
    for c in cols:
        cc = c.lower().replace(' ', '').replace('(', '').replace(')', '').replace('_', '')
        out.append(cc)
    return out

def try_load_from_csvs(root, img_index):
    csvs = glob(os.path.join(root, '**', '*.csv'), recursive=True)
    for csv in csvs:
        try:
            df = pd.read_csv(csv)
        except Exception:
            continue
        raw_cols = list(df.columns)
        norm_cols = normalize_cols(raw_cols)

        # Find ypr columns
        col_map = {}
        for rc, nc in zip(raw_cols, norm_cols):
            if nc.endswith('yaw'):   col_map['yaw'] = rc
            if nc.endswith('pitch'): col_map['pitch'] = rc
            if nc.endswith('roll'):  col_map['roll'] = rc

        # Find path column
        path_candidates = []
        for rc, nc in zip(raw_cols, norm_cols):
            if any(k in nc for k in ['path','image','img','filename','file']):
                path_candidates.append(rc)

        if len(col_map) == 3 and len(path_candidates) >= 1:
            path_col = path_candidates[0]
            tmp = df[[path_col, col_map['yaw'], col_map['pitch'], col_map['roll']]].copy()
            tmp.columns = ['path', 'yaw', 'pitch', 'roll']

            # Make absolute paths; if missing, try by basename lookup
            def fix_path(p):
                pp = str(p)
                if os.path.isabs(pp) and os.path.exists(pp):
                    return pp
                # Try relative to CSV dir
                csv_dir = os.path.dirname(csv)
                cand1 = os.path.join(csv_dir, pp)
                cand2 = os.path.join(root, pp)
                if os.path.exists(cand1): return cand1
                if os.path.exists(cand2): return cand2
                # Try basename in index
                bn = os.path.basename(pp)
                if bn in img_index: return img_index[bn]
                return None

            tmp['path'] = tmp['path'].apply(fix_path)
            tmp = tmp.dropna(subset=['path'])
            # Ensure numeric
            for c in ['yaw','pitch','roll']:
                tmp[c] = pd.to_numeric(tmp[c], errors='coerce')
            tmp = tmp.dropna(subset=['yaw','pitch','roll'])
            # Accept if enough rows
            if len(tmp) >= 500:
                print(f"Loaded labels from CSV: {csv} -> {len(tmp)} rows")
                return tmp.reset_index(drop=True)
    return None

def try_load_from_txts(root, img_index):
    txts = glob(os.path.join(root, '**', '*.txt'), recursive=True)
    for txt in txts:
        try:
            # Try whitespace-delimited reading
            df = pd.read_csv(txt, delim_whitespace=True, header=None, engine='python')
        except Exception:
            continue
        # Heuristic: at least 4 columns where first is path, next three are yaw/pitch/roll
        if df.shape[1] >= 4:
            tmp = df.iloc[:, :4].copy()
            tmp.columns = ['path', 'yaw', 'pitch', 'roll']
            # Path fix
            def fix_path(p):
                pp = str(p)
                txt_dir = os.path.dirname(txt)
                cand1 = os.path.join(txt_dir, pp)
                cand2 = os.path.join(root, pp)
                if os.path.exists(cand1): return cand1
                if os.path.exists(cand2): return cand2
                bn = os.path.basename(pp)
                if bn in img_index: return img_index[bn]
                return None
            tmp['path'] = tmp['path'].apply(fix_path)
            tmp = tmp.dropna(subset=['path'])
            for c in ['yaw','pitch','roll']:
                tmp[c] = pd.to_numeric(tmp[c], errors='coerce')
            tmp = tmp.dropna(subset=['yaw','pitch','roll'])
            if len(tmp) >= 500:
                print(f"Loaded labels from TXT: {txt} -> {len(tmp)} rows")
                return tmp.reset_index(drop=True)
    return None

def load_annotations(root):
    img_index = build_image_index(root)
    df = try_load_from_csvs(root, img_index)
    if df is None:
        df = try_load_from_txts(root, img_index)
    if df is None:
        # Fallback: pair every image with dummy NaNs (will fail gracefully)
        imgs = list_images(root)
        df = pd.DataFrame({'path': imgs, 'yaw': np.nan, 'pitch': np.nan, 'roll': np.nan})
    return df

