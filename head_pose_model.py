# Loss and optimizer
criterion = nn.SmoothL1Loss(beta=1.0)  # robust for angles; you can try L1 as well
optimizer = optim.AdamW(model.parameters(), lr=3e-4, weight_decay=1e-4)
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', patience=2, factor=0.5)

epochs = 100
scaler = torch.cuda.amp.GradScaler(enabled=(device.type == 'cuda'))

def compute_mae(pred, target):
    # pred/target: (N,3) in degrees
    mae = (pred - target).abs().mean(dim=0)  # [yaw_mae, pitch_mae, roll_mae]
    return mae

best_val_mae = float('inf')
best_path = f'/content/best_headpose_{model_name}.pth'

train_losses, val_losses = [], []
train_maes, val_maes = [], []

for epoch in range(1, epochs + 1):
    # Train
    model.train()
    train_loss_sum = 0.0
    train_cnt = 0
    train_mae_sum = torch.zeros(3, device=device)

    for imgs, ypr in train_loader:
        imgs = imgs.to(device)
        ypr = ypr.to(device)

        optimizer.zero_grad(set_to_none=True)
        with torch.cuda.amp.autocast(enabled=(device.type == 'cuda')):
            outputs = model(imgs)  # (N,3) degrees
            loss = criterion(outputs, ypr)
        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        bs = imgs.size(0)
        train_loss_sum += loss.item() * bs
        train_mae_sum += compute_mae(outputs, ypr) * bs
        train_cnt += bs

    avg_train_loss = train_loss_sum / train_cnt
    train_mae = (train_mae_sum / train_cnt).detach().cpu().numpy()

    # ✅ Save training metrics
    train_losses.append(avg_train_loss)
    train_maes.append(train_mae.mean())

    # Validate
    model.eval()
    val_loss_sum = 0.0
    val_cnt = 0
    val_mae_sum = torch.zeros(3, device=device)
    with torch.no_grad():
        for imgs, ypr in val_loader:
            imgs = imgs.to(device)
            ypr = ypr.to(device)
            with torch.cuda.amp.autocast(enabled=(device.type == 'cuda')):
                outputs = model(imgs)
                loss = criterion(outputs, ypr)
            bs = imgs.size(0)
            val_loss_sum += loss.item() * bs
            val_mae_sum += compute_mae(outputs, ypr) * bs
            val_cnt += bs

    avg_val_loss = val_loss_sum / val_cnt
    val_mae = (val_mae_sum / val_cnt).detach().cpu().numpy()
    val_mae_mean = float(val_mae.mean())

    # ✅ Save validation metrics
    val_losses.append(avg_val_loss)
    val_maes.append(val_mae_mean)

    scheduler.step(avg_val_loss)

    print(f"Epoch {epoch:02d}/{epochs} | "
          f"Train Loss: {avg_train_loss:.4f} | "
          f"Train MAE Mean: {train_mae.mean():.2f} deg | "
          f"Val Loss: {avg_val_loss:.4f} | "
          f"Val MAE Mean: {val_mae_mean:.2f} deg")

