def show_sample_predictions(model, dataloader, class_names, num_samples=5, device="cuda"):
    model.eval()
    shown = 0

    with torch.no_grad():
        for images, labels in dataloader:
            images, labels = images.to(device), labels.to(device)
            outputs = model(images)
            probs = F.softmax(outputs, dim=1)
            conf, preds = torch.max(probs, 1)

            for i in range(images.size(0)):
                if shown >= num_samples:
                    return

                img = images[i].cpu().permute(1, 2, 0).numpy()
                img = (img - img.min()) / (img.max() - img.min())  # normalize

                true_label = class_names[labels[i].item()]
                pred_label = class_names[preds[i].item()]
                confidence = conf[i].item() * 100

                plt.imshow(img)
                plt.title(f"Pred: {pred_label} ({confidence:.2f}%)\nTrue: {true_label}")
                plt.axis("off")
                plt.show()

                shown += 1

# Show 5 predictions from validation set
