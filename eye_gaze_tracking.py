def load_best_model(weights_path, num_classes, device):
    mdl = timm.create_model('vit_base_patch16_224', pretrained=False, num_classes=num_classes)
    mdl.load_state_dict(torch.load(weights_path, map_location=device))
    mdl.to(device)
    mdl.eval()
    return mdl

def predict_image(image_path, model, device, class_names):
    img = Image.open(image_path).convert("RGB")
    tensor = inference_transform(img).unsqueeze(0).to(device)
    with torch.no_grad():
        logits = model(tensor)
        probs = torch.softmax(logits, dim=1)[0].cpu().numpy()
        pred_idx = int(np.argmax(probs))
    return class_names[pred_idx], probs[pred_idx], {cls: float(probs[i]) for i, cls in enumerate(class_names)}

