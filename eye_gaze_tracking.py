import os

IMG_EXTS = {'.jpg', '.jpeg', '.png', '.bmp', '.webp'}

def has_images(d):
    for root, _, files in os.walk(d):
        if any(os.path.splitext(f)[1].lower() in IMG_EXTS for f in files):
            return True
    return False

def find_imagefolder_root(root):
    # We’ll look for a directory that has multiple subdirs and those subdirs contain images
    candidates = []
    for dirpath, dirnames, filenames in os.walk(root):
        # Clean dirnames (ignore hidden/system)
        dirnames = [d for d in dirnames if not d.startswith('.')]
        if len(dirnames) >= 2:
            sub_with_imgs = 0
            valid_subs = []
            for d in dirnames:
                dpath = os.path.join(dirpath, d)
                if has_images(dpath):
                    sub_with_imgs += 1
                    valid_subs.append(d)
            if sub_with_imgs >= 2:
                candidates.append((dirpath, sub_with_imgs, valid_subs))
    if not candidates:
        return None, []
    # Choose the candidate with the most subdirs containing images
    candidates.sort(key=lambda x: x[1], reverse=True)
    best_dir, _, subs = candidates[0]
    return best_dir, subs

