# Evaluation
# ----------------------------
def evaluate_model():
    fer_ok = preprocess_fer2013()
    gaze_ok = preprocess_eye_gaze()

    if not fer_ok and not gaze_ok:
        print("❌ No datasets available for evaluation.")
        return

    # Emotion loader
    if fer_ok:
        emo_dataset = ImageFolder("./fer2013/test", transform=transform)
        emo_loader = DataLoader(emo_dataset, batch_size=16, shuffle=False)
        print(f"✅ Emotion test images: {len(emo_dataset)}")

    # Gaze loader
    if gaze_ok:
        gaze_dataset = ImageFolder("./eye_gaze/test", transform=transform)
        gaze_loader = DataLoader(gaze_dataset, batch_size=16, shuffle=False)
        print(f"✅ Gaze test images: {len(gaze_dataset)}")

    # ---- Emotion Evaluation ----
    if fer_ok:
        print("\n🔍 Evaluating Emotion...")
        y_true, y_pred = [], []
        for imgs, labels in emo_loader:
            imgs = imgs.to(device)
            with torch.no_grad():
                out = fusion_model(imgs)
                preds = out["Emotion_class"].cpu().numpy()
            y_true.extend(labels.numpy())
            y_pred.extend(preds)

        acc_emo = accuracy_score(y_true, y_pred)
        print(f"🎭 Emotion Accuracy: {acc_emo*100:.2f}%")

        cm = confusion_matrix(y_true, y_pred)
        ConfusionMatrixDisplay(cm, display_labels=emotion_classes)\
            .plot(cmap=plt.cm.Blues)
        plt.title("Emotion Confusion Matrix")
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.show()
    else:
        acc_emo = 0

    # ---- Gaze Evaluation ----
    if gaze_ok:
        print("\n🔍 Evaluating Eye-Gaze...")
        y_true, y_pred = [], []
        for imgs, labels in gaze_loader:
            imgs = imgs.to(device)
            with torch.no_grad():
                out = fusion_model(imgs)
                preds = out["Gaze_class"].cpu().numpy()
            y_true.extend(labels.numpy())
            y_pred.extend(preds)

        acc_gaze = accuracy_score(y_true, y_pred)
        print(f"👀 Eye-Gaze Accuracy: {acc_gaze*100:.2f}%")

        cm = confusion_matrix(y_true, y_pred)
        ConfusionMatrixDisplay(cm, display_labels=gaze_classes)\
            .plot(cmap=plt.cm.Blues)
        plt.title("Eye-Gaze Confusion Matrix")
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.show()
    else:
        acc_gaze = 0

    # ---- Sample Prediction ----
    if fer_ok and len(emo_dataset) > 0:
        sample_img, sample_label = emo_dataset[0]
        with torch.no_grad():
            pred = fusion_model(sample_img.unsqueeze(0).to(device))
        print("\n📊 Sample Prediction:")
        print("🎭 Emotion:", emotion_classes[pred["Emotion_class"].item()],
              f"(True: {emotion_classes[sample_label]})")
        print("👀 Gaze:", gaze_classes[pred['Gaze_class'].item()] if gaze_ok else "N/A")
        yaw, pitch, roll = pred['HeadPose'][0].cpu().numpy()
        print(f"📐 Head-Pose: Yaw={yaw:.2f}, Pitch={pitch:.2f}, Roll={roll:.2f}")

    # ---- Accuracy Graph ----
    plt.figure(figsize=(6,4))
    labels, scores = [], []
    if acc_emo>0: labels.append("Emotion"); scores.append(acc_emo*100)
    if acc_gaze>0: labels.append("Eye-Gaze"); scores.append(acc_gaze*100)
    if scores:
        plt.bar(labels, scores, color=['skyblue','lightgreen'][:len(scores)])
        plt.ylabel("Accuracy (%)")
        plt.ylim(0,100)
        plt.title("Fusion-Model Accuracy")
        plt.show()
    else:
        print("❌ No accuracy data to display.")

# ----------------------------
# Run
# ----------------------------
if __name__ == "__main__":
    evaluate_model()

