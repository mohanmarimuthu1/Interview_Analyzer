def download_dataset(cmd, zip_path):
    """Run Kaggle CLI command if dataset zip not exists"""
    if not os.path.exists(zip_path):
        print(f"⬇️ Downloading dataset: {zip_path}")
        try:
            subprocess.run(cmd, shell=True, check=True)
        except Exception as e:
            print(f"⚠️ Kaggle CLI download failed: {e}")
            print("👉 Please download manually from Kaggle.")
    else:
        print(f"✅ {zip_path} already exists")

def unzip_dataset(zip_path, dest_dir):
    if os.path.exists(zip_path):
        print(f"📦 Unzipping {zip_path}...")
        with zipfile.ZipFile(zip_path, "r") as z:
            z.extractall(dest_dir)
        print("✅ Unzip done.")
    else:
        print(f"❌ {zip_path} not found, please download first.")

# ----------------------------
# Preprocess FER-2013
# ----------------------------
def preprocess_fer2013():
    fer_csv = "./fer2013/fer2013.csv"
    fer_zip = "./fer2013/fer2013.zip"
    fer_test_dir = "./fer2013/test"

    os.makedirs("./fer2013", exist_ok=True)
    download_dataset("kaggle datasets download -d msambare/fer2013 -p ./fer2013", fer_zip)
    unzip_dataset(fer_zip, "./fer2013")

    if not os.path.exists(fer_csv):
        print("❌ FER-2013 CSV not found after unzip.")
        return False

    print("⚙️  Preprocessing FER-2013...")
    os.makedirs(fer_test_dir, exist_ok=True)
    for emo in emotion_classes:
        os.makedirs(os.path.join(fer_test_dir, emo), exist_ok=True)

    df = pd.read_csv(fer_csv)
    test_df = df[df['Usage'] == 'PublicTest']

    for idx, row in test_df.iterrows():
        emo_label = emotion_classes[row['emotion']]
        pixels = np.array(row['pixels'].split(), dtype=np.uint8).reshape(48,48)
        img = Image.fromarray(pixels).convert("RGB")
        img = img.resize((224,224))
        img.save(os.path.join(fer_test_dir, emo_label, f"{idx}.png"))

    print(f"✅ FER-2013 test set ready: {len(test_df)} images.")
    return True

# ----------------------------
# Preprocess Eye-Gaze
# ----------------------------
def preprocess_eye_gaze():
    gaze_zip = "./eye_gaze/eye-gaze-detection.zip"
    gaze_root = "./eye_gaze"
    gaze_test_dir = "./eye_gaze/test"

    os.makedirs(gaze_root, exist_ok=True)
    download_dataset("kaggle datasets download -d hazemfahmy/eye-gaze-detection -p ./eye_gaze", gaze_zip)
    unzip_dataset(gaze_zip, gaze_root)

    # Create test dir
    os.makedirs(gaze_test_dir, exist_ok=True)
    for cls in gaze_classes:
        os.makedirs(os.path.join(gaze_test_dir, cls), exist_ok=True)

    # Auto-copy jpg/png to proper class folders if dataset has class subfolders
    moved = 0
    for cls in gaze_classes:
        src_dir = os.path.join(gaze_root, cls)
        dest_dir = os.path.join(gaze_test_dir, cls)
        if os.path.exists(src_dir):
            for f in os.listdir(src_dir):
                if f.lower().endswith((".jpg",".jpeg",".png")):
                    try:
                        os.replace(os.path.join(src_dir,f),
                                   os.path.join(dest_dir,f))
                        moved += 1
                    except:
                        pass
    print(f"✅ Eye-Gaze images organized: {moved} files moved.")
    return moved > 0

