import torchvision.transforms as T
from PIL import Image

transform = T.Compose([
    T.Resize((224,224)),
    T.ToTensor(),
    T.Normalize(mean=[0.485,0.456,0.406], std=[0.229,0.224,0.225])
])

def run_inference(image_path):
    img = Image.open(image_path).convert("RGB")
    tensor = transform(img).unsqueeze(0).to(device)

    # Emotion
    with torch.no_grad():
        emo_logits = emotion_model(tensor)
        emo_idx = emo_logits.argmax(dim=1).item()
        emo_label = emotion_classes[emo_idx]

    # Head Pose (yaw, pitch, roll regression)
    with torch.no_grad():
        headpose_pred = headpose_model(tensor)
        yaw, pitch, roll = headpose_pred[0].cpu().numpy()

    # Eye Gaze
    with torch.no_grad():
        gaze_logits = gaze_model(tensor)
        gaze_idx = gaze_logits.argmax(dim=1).item()
        gaze_label = gaze_classes[gaze_idx]

    return {
        "Emotion": emo_label,
        "HeadPose": {"yaw": float(yaw), "pitch": float(pitch), "roll": float(roll)},
        "EyeGaze": gaze_label
    }

